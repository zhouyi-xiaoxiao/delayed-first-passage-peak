#!/usr/bin/env python3
"""Fig. 2: threshold for the disappearance of the delayed peak (release at the sink).

  (a) Threshold curve b_c(theta) for theta in [0.2, 0.8] (stored continuation,
      data/dpma_boundary_generated.csv, mirrored by b_c(theta) = b_c(1-theta)), continued toward
      theta -> 0, 1 by the near-end law B*/min(theta, 1-theta) (B* = 0.7890262), drawn dashed;
      the region under the dashed law is shaded lighter and hatched.  The y axis is clipped at
      b = 10.  The minimum and theta = 1/2 are marked.
  (b) Density at theta = xi = 1/2 for b = 2.5, 3.0, b_c, 3.3, with an inset of the fold region.
  (c) Time and height differences between delayed peak and valley versus delta = b_c - b
      (data/dpma_fold_scaling_generated.csv, written by dpma_saddle_node_certification.py) with
      the normal-form laws 0.0247518 delta^(1/2) and 0.357444 delta^(3/2) (dpma_normal_form.py).

Full text width (7.05 in); TrueType fonts; shared style (figstyle.py); PNG at 150 dpi.
Writes outputs/figures/fig2_threshold.{pdf,png}.
"""
from __future__ import annotations

import csv
import math

import numpy as np
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.ticker import LogLocator, NullFormatter, MultipleLocator
from matplotlib.lines import Line2D

from dpma_saddle_node_bc_theta import phi_vals
import figstyle as S
from paths import DATA, FIGURES, rel

S.apply_style()                  # TrueType (Type 42) fonts, sizes at printed size

B_STAR = 0.7890262          # near-end constant (half-line transform, App. C)
YMAX = 10.0                 # clip of the b axis in panel (a)

# colours (Okabe-Ito; validated for CVD separation)
INK = "#1a1a1a"
MUTED = "#555555"
REGION = "#0072B2"          # boundary / valley+peak region
FILL_COMPUTED = "#cfe3f3"
FILL_ASYMPT = "#eaf2fa"
HATCH = "#8fb5d6"
C_LOW, C_MID, C_HIGH = "#0072B2", "#009E73", "#D55E00"


# ----------------------------------------------------------------- data loaders
def load_boundary_table(path=None):
    """Load the traceable S1=S2 continuation generated by the boundary script."""
    if path is None:
        path = DATA / "dpma_boundary_generated.csv"
    if not path.exists():
        raise FileNotFoundError(
            f"missing {path}; run dpma_saddle_node_bc_theta.py --csv-only first"
        )
    with path.open(newline="") as handle:
        reader = csv.DictReader(handle)
        expected = ["theta", "b_c", "tau_c", "is_min"]
        if reader.fieldnames != expected:
            raise ValueError(f"unexpected boundary columns in {path}: {reader.fieldnames}")
        rows = [
            (
                float(row["theta"]),
                float(row["b_c"]),
                float(row["tau_c"]),
                row["is_min"].strip().lower() == "true",
            )
            for row in reader
        ]
    minima = [row for row in rows if row[3]]
    if len(minima) != 1:
        raise ValueError(f"expected exactly one marked boundary minimum in {path}")
    return rows, minima[0]


def load_fold_scaling_table(path=None):
    """Load the exact seven-point data set used for the reported OLS exponents."""
    if path is None:
        path = DATA / "dpma_fold_scaling_generated.csv"
    if not path.exists():
        raise FileNotFoundError(
            f"missing {path}; run dpma_saddle_node_certification.py first"
        )
    data = np.genfromtxt(path, delimiter=",", names=True)
    expected = ("b", "b_c_minus_b", "tau_gap", "prominence")
    if data.dtype.names != expected or np.atleast_1d(data).size != 7:
        raise ValueError(f"unexpected fold-scaling data in {path}")
    return np.atleast_1d(data)


def interior_pair(xi, th, b, xlo=1e-4, xhi=1.5, n=8000):
    xs = np.exp(np.linspace(math.log(xlo), math.log(xhi), n))
    v = phi_vals(xs, xi, th, b)
    d1 = np.diff(v)
    mx = np.where((d1[:-1] > 0) & (d1[1:] <= 0))[0] + 1
    mn = np.where((d1[:-1] < 0) & (d1[1:] >= 0))[0] + 1
    if len(mx) and len(mn) and mn[0] < mx[-1]:
        return xs[mn[0]], xs[mx[-1]], v[mn[0]], v[mx[-1]]
    return None


# ------------------------------------------------------------------- panel (a)
def panel_a(a):
    boundary_rows, minimum = load_boundary_table()
    continuation = sorted((th, b) for th, b, _, _ in boundary_rows)
    th = np.asarray([row[0] for row in continuation])
    bcv = np.asarray([row[1] for row in continuation])
    half_index = int(np.argmin(np.abs(th - 0.5)))
    if not np.isclose(th[half_index], 0.5, atol=1e-10):
        raise ValueError("generated boundary does not contain theta=0.5")
    bc_half = float(bcv[half_index])
    theta_min, b_min, _, _ = minimum

    # mirror by the symmetry b_c(theta) = b_c(1 - theta)
    mirror = ~np.isclose(th, 0.5, atol=1e-12)
    th_full = np.concatenate([th, 1.0 - th[mirror]])
    bc_full = np.concatenate([bcv, bcv[mirror]])
    order = np.argsort(th_full)
    th_full, bc_full = th_full[order], bc_full[order]
    th_lo, th_hi = float(th_full[0]), float(th_full[-1])          # 0.2, 0.8

    # the computed boundary meets the asymptote at its ends (b_c*theta = 0.789026 there)
    join_err = abs(bc_full[0] * th_lo - B_STAR) / B_STAR
    if join_err > 1e-5:
        raise ValueError(f"computed boundary does not join the endpoint law: {join_err:.2e}")

    # endpoint-law branches, clipped just above the axis top
    th_clip = B_STAR / (YMAX * 1.05)
    t_left = np.linspace(th_clip, th_lo, 300)
    t_left_fill = np.linspace(1e-4, th_lo, 600)
    upper_left = np.minimum(B_STAR / t_left_fill, YMAX * 1.05)

    # shading: computed region (solid tint), asymptotic regions (lighter + hatched)
    a.fill_between(th_full, 0.0, bc_full, facecolor=FILL_COMPUTED, edgecolor="none", lw=0,
                   zorder=1)
    for t_fill in (t_left_fill, 1.0 - t_left_fill):
        a.fill_between(t_fill, 0.0, upper_left, facecolor=FILL_ASYMPT, edgecolor=HATCH,
                       hatch="////", lw=0, zorder=1)

    a.plot(th_full, bc_full, "-", color=REGION, lw=1.6, zorder=3,
           label=r"threshold $b_c(\theta)$")
    a.plot(t_left, B_STAR / t_left, "--", color=REGION, lw=1.3, zorder=3,
           label="near-end law\n" + r"$0.789/\min(\theta,1{-}\theta)$")
    a.plot(1.0 - t_left, B_STAR / t_left, "--", color=REGION, lw=1.3, zorder=3)

    # marked points: minimum (and its mirror image) and theta = 1/2
    for tm in (theta_min, 1.0 - theta_min):
        a.plot(tm, b_min, marker="*", ms=8.5, color=INK, mec="white", mew=0.5, zorder=5)
    a.plot(0.5, bc_half, marker="o", ms=4.8, color=INK, mec="white", mew=0.6, zorder=5)
    a.annotate(
        "minimum" + "\n" + rf"$b_c={b_min:.3f}$" + "\n" + rf"at $\theta={theta_min:.3f}$",
        xy=(theta_min, b_min), xytext=(0.215, 4.75), ha="left", va="center",
        fontsize=6.4, color=INK, linespacing=1.1,
        arrowprops=dict(arrowstyle="-", color=MUTED, lw=0.6, shrinkA=1, shrinkB=4,
                        relpos=(0.45, 0.0)),
        zorder=6,
    )
    a.annotate(
        r"$\theta=1/2$" + "\n" + rf"$b_c={bc_half:.3f}$",
        xy=(0.5, bc_half), xytext=(0.785, 4.75), ha="right", va="center",
        fontsize=6.4, color=INK, linespacing=1.1,
        arrowprops=dict(arrowstyle="-", color=MUTED, lw=0.6, shrinkA=1, shrinkB=3,
                        relpos=(0.0, 0.0)),
        zorder=6,
    )

    # region labels in words
    a.text(0.5, 1.0, "capture spike, valley,\ndelayed peak", ha="center", va="center",
           fontsize=7.2, color="#08406b", fontweight="bold", zorder=6, linespacing=1.15)
    for x_lab in (0.1, 0.9):
        a.text(x_lab, 1.75, "near-end law", rotation=90, ha="center", va="center",
               fontsize=6.4, color="#2f5f8a", zorder=6,
               bbox=dict(boxstyle="square,pad=0.15", facecolor=FILL_ASYMPT,
                         edgecolor="none"))
    a.text(0.5, 5.95, "no delayed peak\n(monotone after the spike)", ha="center",
           va="center", fontsize=S.NOTE_PT, color=INK, linespacing=1.15, zorder=6)

    # divergence of the boundary at the ends
    for x_text, x_tip, ha in ((0.205, 0.087, "left"), (0.795, 0.913, "right")):
        a.annotate("", xy=(x_tip, 9.85), xytext=(x_tip, 8.75),
                   arrowprops=dict(arrowstyle="-|>", color=REGION, lw=0.9,
                                   mutation_scale=7), zorder=6)
    a.text(0.5, 9.3, r"threshold $\to\infty$ as $\theta\to0$ or $1$", ha="center",
           va="center", fontsize=6.8, color=MUTED, zorder=6)

    a.set_xlim(0.0, 1.0)
    a.set_ylim(0.0, YMAX)
    a.xaxis.set_major_locator(MultipleLocator(0.2))
    a.xaxis.set_minor_locator(MultipleLocator(0.1))
    a.yaxis.set_major_locator(MultipleLocator(2))
    a.yaxis.set_minor_locator(MultipleLocator(1))
    a.set_xlabel(r"sink position $\theta$")
    a.set_ylabel(r"sink strength $b$")
    a.tick_params(axis="x", pad=5)        # keep "0.0" clear of the y label "0" at the corner
    S.panel_title(a, "a", r"release at the sink ($\xi=\theta$)")
    leg = a.legend(loc="upper center", bbox_to_anchor=(0.5, 0.9), frameon=True,
                   fontsize=6.3, handlelength=1.6, handletextpad=0.5, borderpad=0.3,
                   labelspacing=0.2,
                   framealpha=0.92, edgecolor="none")
    leg.set_zorder(7)
    return bc_half


# ------------------------------------------------------------------- panel (b)
def panel_b(a, bc_half):
    xs = np.exp(np.linspace(math.log(1e-3), math.log(0.3), 3000))
    curves = [
        (2.5, C_LOW, "-", 1.2, r"$2.5$"),
        (3.0, C_MID, "-.", 1.2, r"$3.0$"),
        (bc_half, INK, "--", 1.2, r"$b_c$"),
        (3.3, C_HIGH, ":", 1.5, r"$3.3$"),
    ]
    values = {b: phi_vals(xs, 0.5, 0.5, b) for b, *_ in curves}
    for b, colour, ls, lw, label in curves:
        a.plot(xs, values[b], color=colour, ls=ls, lw=lw, label=label)
    a.set_xscale("log")
    a.set_xlim(1e-3, 0.3)
    a.set_xlabel(r"time $\tau$")
    a.set_ylabel(r"absorption-time density $\Phi(\tau)$")
    S.panel_title(a, "b", r"density, $\theta=\xi=1/2$")
    a.legend(loc="upper left", bbox_to_anchor=(0.11, 1.0), frameon=False, title=r"$b$",
             title_fontsize=7, handlelength=1.8, borderaxespad=0.3, labelspacing=0.2)

    # inset: the fold region (valley and peak merging), invisible at full scale
    axins = a.inset_axes([0.585, 0.40, 0.39, 0.56])
    for b, colour, ls, lw, _ in curves:
        axins.plot(xs, values[b], color=colour, ls=ls, lw=lw)
    tmn, tmx, vmn, vmx = interior_pair(0.5, 0.5, 2.5)        # widest fold sets the zoom
    axins.set_xlim(0.55 * tmn, 1.7 * tmx)
    axins.set_ylim(vmn - 0.35, vmx + 0.35)
    axins.tick_params(labelsize=6, length=2)
    axins.set_xticks([0.03, 0.06])
    a.indicate_inset_zoom(axins, edgecolor=MUTED, lw=0.6)


# ------------------------------------------------------------------- panel (c)
def panel_c(a):
    scaling = load_fold_scaling_table()
    dd = scaling["b_c_minus_b"]
    gg = scaling["tau_gap"]
    pp = scaling["prominence"]
    a.loglog(dd, gg, "o", ms=4, color=C_LOW, zorder=4)
    a.loglog(dd, pp, "s", ms=3.8, color=C_HIGH, zorder=4)
    # analytic normal-form prefactors (dpma_normal_form.py):
    # 2*sqrt(2*S1b/S3) and (4*sqrt2/3)*S1b^1.5/sqrt(S3)
    a.loglog(dd, 0.0247518 * dd ** 0.5, "--", lw=1.0, color=C_LOW, zorder=3)
    a.loglog(dd, 0.357444 * dd ** 1.5, "--", lw=1.0, color=C_HIGH, zorder=3)
    # fit laws written next to their lines; legend names the two data sets
    a.text(3.2e-3, 7.2e-4, r"$0.02475\,\delta^{1/2}$", color=C_LOW, fontsize=S.NOTE_PT,
           ha="center", va="top")
    a.text(8.0e-3, 1.05e-4, r"$0.35744\,\delta^{3/2}$", color=C_HIGH, fontsize=S.NOTE_PT,
           ha="left", va="center")
    hd = [Line2D([], [], color=C_LOW, ls="--", lw=1.0, marker="o", ms=4),
          Line2D([], [], color=C_HIGH, ls="--", lw=1.0, marker="s", ms=3.8)]
    a.legend(hd, [r"time gap $\tau_+-\tau_-$", r"height gap $\Phi(\tau_+)-\Phi(\tau_-)$"],
             loc="upper left", frameon=False, handlelength=1.8, borderaxespad=0.3,
             labelspacing=0.3)
    a.set_ylim(1.5e-5, 2.2e-2)          # headroom for the legend above the data
    a.set_xlabel(r"distance to threshold $\delta=b_c-b$")
    a.set_ylabel("peak$-$valley separation")
    a.xaxis.set_major_locator(LogLocator(base=10, numticks=4))
    a.xaxis.set_minor_locator(LogLocator(base=10, subs=np.arange(2, 10) * 0.1))
    a.xaxis.set_minor_formatter(NullFormatter())
    S.panel_title(a, "c", "approach to the threshold")


def check_text_inside(fig, dpi=300):
    """Fail if drawn content (incl. axis labels, titles, annotations, legends and the
    visible tick labels) extends beyond the canvas, i.e. would be silently clipped."""
    from matplotlib.text import Text

    fig.set_dpi(dpi)
    fig.canvas.draw()
    renderer = fig.canvas.get_renderer()
    width, height = fig.get_size_inches() * dpi
    boxes = [ax.get_tightbbox(renderer) for ax in fig.axes]
    tick_texts = set()
    for ax in fig.axes:
        tick_texts.update(ax.get_xticklabels(which="both"))
        tick_texts.update(ax.get_yticklabels(which="both"))
    for text in fig.findobj(Text):
        if text in tick_texts or not text.get_visible() or not text.get_text():
            continue
        boxes.append(text.get_window_extent(renderer))
    for box in boxes:
        if box.x0 < -1 or box.y0 < -1 or box.x1 > width + 1 or box.y1 > height + 1:
            raise RuntimeError(f"content overflows the {width:.0f}x{height:.0f} canvas: {box}")


def main():
    fig, axes = plt.subplots(
        1, 3, figsize=(7.05, 2.95),
        gridspec_kw=dict(width_ratios=[1.24, 1.0, 1.08]),
    )
    bc_half = panel_a(axes[0])
    panel_b(axes[1], bc_half)
    panel_c(axes[2])
    fig.tight_layout(pad=0.3, w_pad=1.0, rect=(0.0, 0.0, 0.99, 1.0))
    check_text_inside(fig)

    info = S.save(fig, FIGURES, "fig2_threshold")   # layout/font checks, PDF + PNG (150 dpi)
    print("wrote", rel(info["pdf"]), "and .png", f"({S.PNG_DPI} dpi);",
          f"{info['width_in']:.2f} x {info['height_in']:.2f} in")


if __name__ == "__main__":
    main()
